function [R1, p1, info] = Roomframe_plane(P1)
% 平面拟合构造房间系(站 1 系 -> 构造房间系, 仅显示/锚定用)
%
% 背景: 双站互标定只给相对位姿, 站 1 绝对位姿不可观(全局 6 自由度规范自由)。
% 目标同水平面运动先验下, 对站 1 点云做平面拟合, 数据可观 3 个自由度:
%   法向 -> 房间竖直方向(2 自由度); 偏距 -> 雷达离目标平面的垂直距离 d(1)。
% 其余 3 个为纯约定: 偏航 = 站 1 波束的水平投影方向(房间 x), 原点 = 站 1
% 正下方, 目标平面 = z 0。注意该系不是墙对齐的物理房间系。
%
% 输入: P1 (N,3) 站 1 系点云(建议用配准内点), N >= 3 且不共线
% 输出: R1 (3,3) 旋转, C_w = R1*C_s + p1(行 = 房间轴在站 1 系的表达)
%       p1 (3,1) 站 1 原点在构造系的坐标 = [0; 0; d]
%       info.d   雷达到目标平面垂直距离 (m)
%       info.rms 平面拟合正交残差 RMS (m, 共面性质量)
%       info.nrm 拟合平面法向(站 1 系, 符号未定)
%
% 实现(Echo_Simulation_Design.md §10.4): 去质心 SVD, 最小奇异向量 = 法向;
% 房间 z 轴 = -sign(d)*n(平面指向雷达一侧为上); 房间 x 轴 = boresight
% [1;0;0] 去竖直分量归一化; y = z × x。

    mu = mean(P1, 1).';                    % (3,1) 质心
    X  = P1 - mu.';                        % (N,3) 去质心
    [~, S, V] = svd(X, 0);
    n  = V(:, end);                        % 最小奇异向量 = 平面法向(站 1 系)
    d0 = n.' * mu;                         % 有符号偏距
    if abs(d0) < eps
        error('点云过原点, 平面偏距为零, 构造退化');
    end
    z_ax = -sign(d0) * n;                  % 房间 z 轴(平面 -> 雷达一侧为上)

    b = [1; 0; 0];                         % 站 1 boresight(站系内恒为 x 轴)
    x_ax = b - (b.' * z_ax) * z_ax;        % 去竖直分量 = 水平投影
    if norm(x_ax) < 1e-6
        error('波束与平面法向共线, 偏航约定退化');
    end
    x_ax = x_ax / norm(x_ax);
    y_ax = cross(z_ax, x_ax);

    R1 = [x_ax.'; y_ax.'; z_ax.'];
    p1 = [0; 0; abs(d0)];

    info.d   = abs(d0);
    info.rms = S(end, end) / sqrt(size(P1, 1));   % 正交残差 RMS
    info.nrm = n;
end
